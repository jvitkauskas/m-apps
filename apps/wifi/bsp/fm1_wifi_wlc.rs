//! The coexistence controller's ("WLC") set-up, as the JieLi AC79 SDK's cpu.a wlc.c writes it when Wi-Fi starts on a
//! radio BT has started (usb_register -> wlc_main -> wlc_init, coexistence index 0): every word written to the WLC port
//! 0x14004, in order, after 0x14000 |= 3 (fm1_wifi.rs `up`). Taken from an emulator capture (Optimist's
//! tools/wifi_capture, docs/WIFI-HW-FACTS.md §2b there). Stock V15 never writes this port.
//! The words are JieLi's: Copyright (c) 2024-2026 Zhuhai Jieli Technology Co., Ltd., published under Apache-2.0 in its
//! AC79 AIoT SDK, https://gitee.com/Jieli-Tech/fw-AC79_AIoT_SDK (cpu/wl82/liba/cpu.a, wlc.c).
//! Changed by Optimist (Apache-2.0 section 4(b)): not the code but the writes it made, recorded in the emulator by
//! tools/wifi_capture and listed here as data; then packed (below). Changed by m-apps: the same values as Rust statics
//! (tools/c_tables.py, from fm1_wifi_wlc.h).

pub const PORT: u32 = 0x14004;
/// Stored packed (2026-10-27, to save flash): every word is a 16-bit value in the top half and a code (c << 4 | 1, c
/// below 256) in the bottom, so the table is two arrays, 1,695 bytes in place of 2,260; [`word`] puts the words back
/// together. fm1-base's tests/wifi/wifi_wlc_test.c checks that they come back as they were, word for word.
pub const N: usize = 565;

/// Word i, as it's written.
#[inline(always)]
pub fn word(i: usize) -> u32 {
    u32::from(HI[i]) << 16 | u32::from(C[i]) << 4 | 1
}

